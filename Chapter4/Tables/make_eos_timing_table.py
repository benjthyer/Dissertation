"""
Wall time to evaluate N = 2**15 HeFESTo Earth assemblages with the emulator and successively
more terms of the nGibbs HeFESTo EOS, on the CPU and the GPU, against HeFESTo itself.

Reads each machine's CSVs (no model, no GPU needed) and writes tab_eos_terms_timing.tex, one
CPU and one GPU row per machine:

    performance_results.csv          performance_benchmarking.py
    benchmark_results_hefesto.csv    benchmark_hefesto.sh (run in WSL)

from ../Figures/generated/ (laptop) and ../Figures/source/desktop_performance/ (desktop).

The property columns of performance_results.csv are timed separately from the emulator and
each holds every term up to its level (isomorphic, metamorphic = isomorphic + phase-change
terms, +fast = all), so each column of the table is the emulator time plus one of them.
HeFESTo was not run at N = 2**15: its time is that machine's fastest measured rate
(assemblages per second, over the worker counts) times N, as for the dotted lines of
benchmark_combined_time_machines.pdf through a single run. HeFESTo runs on the CPU only.

Usage
    python make_eos_timing_table.py
"""
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
MACHINES = {                                  # row label -> directory holding its CSVs
    'Laptop': HERE.parent / 'Figures' / 'generated',
    'Desktop': HERE.parent / 'Figures' / 'source' / 'desktop_performance',
}
N = 2 ** 15
LEVELS = ('isomorphic', 'metamorphic', '+fast')


def _n(x):
    """Integer with LaTeX thousands separators: 32768 -> 32{,}768."""
    return f'{x:,.0f}'.replace(',', '{,}')


def _s(t):
    """Seconds to three significant figures."""
    if t >= 1000:
        return _n(t)
    return f'{t:#.3g}' if t >= 1 else f'{t:.2f}'


def _r(x, step):
    """Round to a multiple of `step` for prose: 33690 -> 33{,}700."""
    return _n(round(x / step) * step)


def main():
    rows, hef_notes, T = [], [], {}
    for machine, csv_dir in MACHINES.items():
        emu = pd.read_csv(csv_dir / 'performance_results.csv').set_index('Batch Size').loc[N]
        hef = pd.read_csv(csv_dir / 'benchmark_results_hefesto.csv')
        hef['rate'] = hef['assemblages'] / hef['t_s']
        best = hef.loc[hef['rate'].idxmax()]
        t_hef = N / best['rate']
        hef_notes.append(f"{int(best['jobs'])} parallel workers on the {machine.lower()}, from "
                         f"{_n(best['assemblages'])} assemblages in {_n(best['t_s'])}\\,s")

        for dev in ('CPU', 'GPU'):
            t_emu = emu[f'{dev} Emulator']
            cells = [t_emu] + [t_emu + emu[f'{dev} Properties ({v})'] for v in LEVELS]
            T[machine, dev] = cells + [t_hef]
            cells = [_s(t) for t in cells] + [_s(t_hef) if dev == 'CPU' else '--']
            rows.append(f'{machine} {dev} & ' + ' & '.join(cells) + r' \\')
            print(f'{machine} {dev}: ' + ', '.join(cells))

    lap, desk = T['Laptop', 'CPU'], T['Desktop', 'CPU']
    lapg, deskg = T['Laptop', 'GPU'], T['Desktop', 'GPU']
    macros = {                                    # prose numbers of the performance paragraph
        'EosTimingN': _n(N),
        'EosHefLaptop': _r(lap[4], 100), 'EosHefDesktop': _r(desk[4], 100),
        'EosEmuLo': f'{min(lap[0], desk[0]):.1f}', 'EosEmuHi': f'{max(lap[0], desk[0]):.1f}',
        'EosEmuSpeedLo': _r(desk[4] / desk[0], 1000), 'EosEmuSpeedHi': _r(lap[4] / lap[0], 1000),
        'EosGpuEmuLo': _s(deskg[0]), 'EosGpuEmuHi': _s(lapg[0]),
        'EosFullDesktop': _s(desk[3]), 'EosFullLaptop': _s(lap[3]),
        'EosFullSpeedLo': _r(desk[4] / desk[3], 10), 'EosFullSpeedHi': _r(lap[4] / lap[3], 100),
        'EosGpuIsoDesktop': _s(deskg[1]), 'EosGpuIsoLaptop': f'{lapg[1]:.1f}',
    }
    mac = HERE / 'tab_eos_terms_timing_macros.tex'
    header = '% Generated by Chapter4/Tables/make_eos_timing_table.py -- do not edit by hand.\n'
    body = ''.join('\\newcommand{\\%s}{%s}\n' % kv for kv in macros.items())
    mac.write_text(header + body, encoding='utf-8')

    tex = rf"""% Generated by Chapter4/Tables/make_eos_timing_table.py -- do not edit by hand.
\begin{{table}}[!htbp]
\centering
\small
\caption{{Wall time (s) to evaluate $N = 2^{{15}}$ ({_n(N)}) assemblages along the \textsc{{HeFESTo}} Earth isentrope of
\S\ref{{ch4-benchmarking}} on the laptop (4-core Intel i7-11370H CPU and NVIDIA GeForce RTX 3060 GPU with 6 GB VRAM) and the desktop (20-core Intel i7-14700H CPU and
NVIDIA GeForce RTX 5070 Ti GPU with 16 GB of VRAM). Emulator: the
isentropic emulator alone (phase equilibria, mass balance and temperature). Each further column adds the \emph{{nGibbs}}
equations of state with successively more terms (Fig.~\ref{{fig:ch4-eos-terms}}): the isomorphic properties only, then
the metamorphic (phase-change) terms, then the order-disorder (``fast'') relaxation of $V_P$. \textsc{{HeFESTo}}:
extrapolated linearly from the fastest measured run on each machine ({'; '.join(hef_notes)}).}}
\label{{tab:ch4-eos-terms-timing}}
\begin{{tabular}}{{@{{}}lrrrrr@{{}}}}
\toprule
 & Emulator & + isomorphic & + metamorphic & + fast & \textsc{{HeFESTo}} \\
\midrule
{rows[0]}
{rows[1]}
\midrule
{rows[2]}
{rows[3]}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    out = HERE / 'tab_eos_terms_timing.tex'
    out.write_text(tex, encoding='utf-8')
    print(f'  -> {out}')


if __name__ == '__main__':
    main()
